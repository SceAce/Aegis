// Aegis C6-F — registered, read-only external test runner.
//
// The code-repair Oracle decides success by running an EXTERNAL test file that
// lives in the workspace but is NOT the model's write target. This module runs
// it as a real child process through a HOST-OWNED harness.
//
// Why a harness: a bare `node check.mjs` trusts `process.exit(0)`. A target
// module that ends the process before the test's assertions run would look like
// a pass. The harness therefore uses a MINIMAL TRUSTED HOST COMPLETION PROTOCOL:
//
//   1. verify the registered test's identity (digest) BEFORE running;
//   2. import the test module and write the completion record ONLY after the
//      import RESOLVES (every top-level assertion executed) or REJECTS (an
//      assertion failed) — an early `process.exit` from the test or a dependency
//      resolves NOTHING and yields NO record, so the result is `unknown`;
//   3. never derive trust from target-controlled text: the harness does NOT read
//      a stack, does NOT treat a printed "PASSED" line as authority, and does NOT
//      enter any special handling on `process.exit`/`Error.prepareStackTrace`;
//   4. the completion record carries a random nonce generated by the Host, so a
//      stale or foreign result file cannot authenticate completion.
//
// Honest boundary: the workspace is not an OS sandbox; the test file is trusted
// HOST input and the model's target is a different file. The completion protocol
// raises the bar for a normal target module; it is not a claim of OS-level
// isolation from an arbitrary hostile process.

import { spawnSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

import { digest } from "../fixture/contracts.mjs";

export const REGISTERED_TEST_VERSION = "3.0.0";

/**
 * The Host-owned harness source. It is written to a directory OUTSIDE the
 * model's writable target so the model can neither read nor rewrite it. It
 * imports the registered test and writes a completion record only after the
 * import RESOLVES or REJECTS; a `process.exit` raised before that point produces
 * no record, so the caller sees `unknown`.
 *
 * @param {string} testAbsolute
 * @param {string} resultPath
 * @param {string} nonce
 * @returns {string}
 */
function harnessSource(testAbsolute, resultPath, nonce) {
	return [
		'import { writeFileSync } from "node:fs";',
		`const RESULT = ${JSON.stringify(resultPath)};`,
		`const TEST = ${JSON.stringify(testAbsolute)};`,
		`const NONCE = ${JSON.stringify(nonce)};`,
		"let written = false;",
		"const write = (record) => {",
		"  if (written) return;",
		"  written = true;",
		"  try { writeFileSync(RESULT, JSON.stringify({ ...record, nonce: NONCE })); } catch {}",
		"};",
		// No `process.exit` patch, no `Error.prepareStackTrace` read, no stack text.
		// The ONLY completion signal is that the imported test's top-level
		// evaluation finished (resolved) or raised (rejected).
		"try {",
		"  await import(TEST);",
		"  write({ complete: true, failed: 0, error: null });",
		"} catch (error) {",
		"  write({ complete: true, failed: 1, error: String(error && error.message ? error.message : error) });",
		"}",
		"",
	].join("\n");
}

/**
 * Run a registered test file inside the workspace through the Host harness.
 * Returns the REAL observed result. A missing test file, an early process exit,
 * a timeout, or a missing/mismatched completion record is a harness error
 * (unknown), never a pass.
 *
 * @param {{
 *   workspaceRoot: string,
 *   testFile?: string,
 *   nodePath?: string,
 *   timeoutMs?: number,
 *   expectedTestDigest?: string|null,
 *   harnessDir?: string|null,
 * }} args
 * @returns {{
 *   ok: boolean, passed: number|null, failed: number|null, complete: boolean,
 *   assertions: number|null, detail: string, exit_code: number|null,
 *   test_digest: string|null, test_identity_ok: boolean, forged_output: boolean,
 * }}
 */
export function runRegisteredTest(
	{
		workspaceRoot,
		testFile = "check.mjs",
		nodePath = process.execPath,
		timeoutMs = 10000,
		expectedTestDigest = null,
		harnessDir = null,
	} = /** @type {any} */ ({}),
) {
	const unknown = (detail, extra = {}) => ({
		ok: false,
		passed: null,
		failed: null,
		complete: false,
		assertions: null,
		detail,
		exit_code: null,
		test_digest: null,
		test_identity_ok: false,
		forged_output: false,
		...extra,
	});
	const absolute = resolve(workspaceRoot, testFile);
	if (!existsSync(absolute)) return unknown(`registered test not found: ${testFile}`);
	const testDigest = digest(readFileSync(absolute, "utf8"));
	if (typeof expectedTestDigest === "string" && expectedTestDigest && testDigest !== expectedTestDigest) {
		return unknown("registered test identity changed before execution", {
			test_digest: testDigest,
			test_identity_ok: false,
		});
	}

	// The harness + result live OUTSIDE the target workspace so the model's write
	// target cannot read or replace them. The nonce is generated per run and is
	// never written to disk before the harness completes, so a stale or foreign
	// result file cannot authenticate a completion.
	const nonce = randomUUID();
	const runtimeDir = harnessDir ?? join(dirname(absolute), "..", `.aegis-harness-${process.pid}-${Date.now()}`);
	mkdirSync(runtimeDir, { recursive: true });
	const harnessPath = join(runtimeDir, "registered-test-harness.mjs");
	const resultPath = join(runtimeDir, "result.json");
	writeFileSync(harnessPath, harnessSource(absolute, resultPath, nonce), "utf8");
	try {
		rmSync(resultPath, { force: true });
		const result = spawnSync(nodePath, [harnessPath], {
			cwd: workspaceRoot,
			timeout: timeoutMs,
			encoding: "utf8",
			stdio: ["ignore", "pipe", "pipe"],
		});
		const exitCode = typeof result.status === "number" ? result.status : null;
		const output = `${result.stdout ?? ""}${result.stderr ?? ""}`;
		const signaled = Boolean(result.signal);
		// The completion record is the ONLY pass condition. Its absence (early
		// process exit, timeout, crash before the import resolves) is UNKNOWN.
		let record = null;
		try {
			record = JSON.parse(readFileSync(resultPath, "utf8"));
		} catch {
			record = null;
		}
		const nonceOk = Boolean(record && record.nonce === nonce);
		if (!record || record.complete !== true || !nonceOk) {
			return unknown(
				`registered test produced no trusted complete result (exit=${String(exitCode)}${signaled ? `, signal=${result.signal}` : ""}); the acceptance assertions were not confirmed`,
				{ exit_code: exitCode, test_digest: testDigest, test_identity_ok: true, forged_output: /PASSED=/.test(output) },
			);
		}
		const failed = Number.isInteger(record.failed) ? record.failed : 1;
		// A printed PASSED line is not the authority; the harness completion is.
		const ok = failed === 0 && exitCode === 0;
		return {
			ok,
			passed: null,
			failed,
			complete: true,
			assertions: null,
			test_digest: testDigest,
			test_identity_ok: true,
			forged_output: false,
			exit_code: exitCode,
			detail: ok
				? "registered test completed its top-level assertions and passed"
				: `registered test failed (exit=${String(exitCode)}): ${record.error ?? output.slice(-300)}`,
		};
	} finally {
		rmSync(runtimeDir, { recursive: true, force: true });
	}
}
